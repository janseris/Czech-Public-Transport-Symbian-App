/* Hand-written ARM (ARMv4, ARM state, interworking returns) memory helpers for Symbian EKA1 phones
 * (Nokia 9300 / S80 2.0, GCC 2.9 armi). Only built when FM_ASM is set (fastmem.h); fastmem_ref.c has the
 * same functions in C for every other build.
 *
 * fm_memcpy: the destination is aligned first, then 32 bytes per LDM/STM pair; a source that is
 *            not word aligned after that is merged from aligned words with shifts (little-endian).
 *            Forward only, like the C version (fine for dst < src overlaps).
 * fm_memset: aligned, then 32 bytes per STM.
 * fm_strlen: aligned, then a word at a time ((w - 0x01010101) & ~w & 0x80808080 finds a zero byte).
 * fm_fill16: 16-bit values (a 16 bpp frame buffer, a z-buffer), 16 at a time per STM.
 * fm_fill32: 32-bit values, 8 at a time per STM.
 *
 * Byte loops on the ARM9 cost ~5 cycles a byte (load-use stall, two branches per byte with GCC
 * 2.9); LDM/STM moves 32 bytes in about 20. */

#include "fastmem.h"

#ifdef FM_ASM

__asm__(
"	.text\n"
"	.align 2\n"
"	.global fm_memcpy\n"
"fm_memcpy:\n"
"	cmp	r2, #8\n"
"	bcc	.Lmc_bytes\n"
"	ands	r3, r0, #3\n"
"	beq	.Lmc_dalign\n"
"	rsb	r3, r3, #4\n"
"	sub	r2, r2, r3\n"
".Lmc_head:\n"
"	ldrb	ip, [r1], #1\n"
"	subs	r3, r3, #1\n"
"	strb	ip, [r0], #1\n"
"	bne	.Lmc_head\n"
".Lmc_dalign:\n"
"	ands	r3, r1, #3\n"
"	bne	.Lmc_shift\n"
"	subs	r2, r2, #32\n"
"	bcc	.Lmc_w4\n"
"	stmfd	sp!, {r4-r8, lr}\n"
".Lmc_32:\n"
"	ldmia	r1!, {r3-r8, ip, lr}\n"
"	subs	r2, r2, #32\n"
"	stmia	r0!, {r3-r8, ip, lr}\n"
"	bcs	.Lmc_32\n"
"	ldmfd	sp!, {r4-r8, lr}\n"
".Lmc_w4:\n"
"	adds	r2, r2, #28\n"
"	bcc	.Lmc_w4done\n"
".Lmc_w4l:\n"
"	ldr	r3, [r1], #4\n"
"	subs	r2, r2, #4\n"
"	str	r3, [r0], #4\n"
"	bcs	.Lmc_w4l\n"
".Lmc_w4done:\n"
"	add	r2, r2, #4\n"
".Lmc_bytes:\n"
"	subs	r2, r2, #1\n"
"	bxcc	lr\n"
".Lmc_bl:\n"
"	ldrb	r3, [r1], #1\n"
"	subs	r2, r2, #1\n"
"	strb	r3, [r0], #1\n"
"	bcs	.Lmc_bl\n"
"	bx	lr\n"
/* the source is r3 (1..3) bytes past a word boundary; r2 >= 4 here */
".Lmc_shift:\n"
"	stmfd	sp!, {r4, lr}\n"
"	bic	r1, r1, #3\n"
"	ldr	ip, [r1], #4\n"
"	sub	r2, r2, #4\n"
"	cmp	r3, #2\n"
"	beq	.Lmc_s16\n"
"	bhi	.Lmc_s24\n"
".Lmc_s8:\n"
"	mov	r4, ip, lsr #8\n"
"	ldr	ip, [r1], #4\n"
"	subs	r2, r2, #4\n"
"	orr	r4, r4, ip, lsl #24\n"
"	str	r4, [r0], #4\n"
"	bcs	.Lmc_s8\n"
"	sub	r1, r1, #3\n"
"	b	.Lmc_sdone\n"
".Lmc_s16:\n"
"	mov	r4, ip, lsr #16\n"
"	ldr	ip, [r1], #4\n"
"	subs	r2, r2, #4\n"
"	orr	r4, r4, ip, lsl #16\n"
"	str	r4, [r0], #4\n"
"	bcs	.Lmc_s16\n"
"	sub	r1, r1, #2\n"
"	b	.Lmc_sdone\n"
".Lmc_s24:\n"
"	mov	r4, ip, lsr #24\n"
"	ldr	ip, [r1], #4\n"
"	subs	r2, r2, #4\n"
"	orr	r4, r4, ip, lsl #8\n"
"	str	r4, [r0], #4\n"
"	bcs	.Lmc_s24\n"
"	sub	r1, r1, #1\n"
".Lmc_sdone:\n"
"	ldmfd	sp!, {r4, lr}\n"
"	add	r2, r2, #4\n"
"	b	.Lmc_bytes\n"

"	.align 2\n"
"	.global fm_memset\n"
"fm_memset:\n"
"	and	r1, r1, #255\n"
"	cmp	r2, #8\n"
"	bcc	.Lms_bytes\n"
"	orr	r1, r1, r1, lsl #8\n"
"	orr	r1, r1, r1, lsl #16\n"
".Lms_head:\n"
"	tst	r0, #3\n"
"	strneb	r1, [r0], #1\n"
"	subne	r2, r2, #1\n"
"	bne	.Lms_head\n"
"	subs	r2, r2, #32\n"
"	bcc	.Lms_w4\n"
"	stmfd	sp!, {r4-r7}\n"
"	mov	r3, r1\n"
"	mov	r4, r1\n"
"	mov	r5, r1\n"
"	mov	r6, r1\n"
"	mov	r7, r1\n"
"	mov	ip, r1\n"
".Lms_32:\n"
"	stmia	r0!, {r1, r3-r7, ip}\n"
"	str	r1, [r0], #4\n"
"	subs	r2, r2, #32\n"
"	bcs	.Lms_32\n"
"	ldmfd	sp!, {r4-r7}\n"
".Lms_w4:\n"
"	adds	r2, r2, #28\n"
"	bcc	.Lms_w4done\n"
".Lms_w4l:\n"
"	str	r1, [r0], #4\n"
"	subs	r2, r2, #4\n"
"	bcs	.Lms_w4l\n"
".Lms_w4done:\n"
"	add	r2, r2, #4\n"
".Lms_bytes:\n"
"	subs	r2, r2, #1\n"
"	bxcc	lr\n"
".Lms_bl:\n"
"	strb	r1, [r0], #1\n"
"	subs	r2, r2, #1\n"
"	bcs	.Lms_bl\n"
"	bx	lr\n"

"	.align 2\n"
"	.global fm_strlen\n"
"fm_strlen:\n"
"	movs	r1, r0\n"
"	bxeq	lr\n"
".Lsl_head:\n"
"	tst	r1, #3\n"
"	beq	.Lsl_words\n"
"	ldrb	r2, [r1], #1\n"
"	cmp	r2, #0\n"
"	bne	.Lsl_head\n"
"	b	.Lsl_end\n"
".Lsl_words:\n"
"	mov	ip, #1\n"
"	orr	ip, ip, ip, lsl #8\n"
"	orr	ip, ip, ip, lsl #16\n"
".Lsl_wl:\n"
"	ldr	r2, [r1], #4\n"
"	sub	r3, r2, ip\n"
"	bic	r3, r3, r2\n"
"	tst	r3, ip, lsl #7\n"
"	beq	.Lsl_wl\n"
"	sub	r1, r1, #4\n"
".Lsl_tail:\n"
"	ldrb	r2, [r1], #1\n"
"	cmp	r2, #0\n"
"	bne	.Lsl_tail\n"
".Lsl_end:\n"
"	sub	r0, r1, r0\n"
"	sub	r0, r0, #1\n"
"	bx	lr\n"
"	.align 2\n"
"	.global fm_fill16\n"
"fm_fill16:\n"
"	mov	r1, r1, lsl #16\n"
"	orr	r1, r1, r1, lsr #16\n"
"	cmp	r2, #0\n"
"	bxeq	lr\n"
"	tst	r0, #2\n"
"	beq	.Lf16_al\n"
"	strh	r1, [r0], #2\n"
"	subs	r2, r2, #1\n"
"	bxeq	lr\n"
".Lf16_al:\n"
"	subs	r2, r2, #16\n"
"	bcc	.Lf16_w\n"
"	stmfd	sp!, {r4-r7, lr}\n"
"	mov	r3, r1\n"
"	mov	r4, r1\n"
"	mov	r5, r1\n"
"	mov	r6, r1\n"
"	mov	r7, r1\n"
"	mov	ip, r1\n"
"	mov	lr, r1\n"
".Lf16_32:\n"
"	stmia	r0!, {r1, r3-r7, ip, lr}\n"
"	subs	r2, r2, #16\n"
"	bcs	.Lf16_32\n"
"	ldmfd	sp!, {r4-r7, lr}\n"
".Lf16_w:\n"
"	adds	r2, r2, #14\n"
"	bcc	.Lf16_wd\n"
".Lf16_wl:\n"
"	str	r1, [r0], #4\n"
"	subs	r2, r2, #2\n"
"	bcs	.Lf16_wl\n"
".Lf16_wd:\n"
"	adds	r2, r2, #2\n"
"	strneh	r1, [r0]\n"
"	bx	lr\n"

"	.align 2\n"
"	.global fm_fill32\n"
"fm_fill32:\n"
"	subs	r2, r2, #8\n"
"	bcc	.Lf32_t\n"
"	stmfd	sp!, {r4-r7, lr}\n"
"	mov	r3, r1\n"
"	mov	r4, r1\n"
"	mov	r5, r1\n"
"	mov	r6, r1\n"
"	mov	r7, r1\n"
"	mov	ip, r1\n"
"	mov	lr, r1\n"
".Lf32_32:\n"
"	stmia	r0!, {r1, r3-r7, ip, lr}\n"
"	subs	r2, r2, #8\n"
"	bcs	.Lf32_32\n"
"	ldmfd	sp!, {r4-r7, lr}\n"
".Lf32_t:\n"
"	adds	r2, r2, #8\n"
"	bxeq	lr\n"
".Lf32_tl:\n"
"	str	r1, [r0], #4\n"
"	subs	r2, r2, #1\n"
"	bne	.Lf32_tl\n"
"	bx	lr\n"
);

#endif
